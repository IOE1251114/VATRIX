/* Generates the two files that keep answers out of the website:
 *   src/domain/questions.json  – what students see (no answers, no explanations). Committed.
 *   supabase/answer-key.sql    – loads the answers into the database table `problem_key`. Git-ignored.
 * Source of truth: src/domain/{daa,ds,la}/problems.ts. Run with `npm run gen:problems`
 * after editing any problem, then run answer-key.sql in the Supabase SQL Editor. */
import { writeFileSync } from "node:fs";
import { answerKey } from "../src/domain/answerKey";
import { toPublic } from "../src/domain/problemKit";

const ids = new Set<string>();
for (const p of answerKey) {
  if (ids.has(p.id)) throw new Error(`Duplicate problem id: ${p.id}`);
  ids.add(p.id);
}

writeFileSync(
  "src/domain/questions.json",
  JSON.stringify(answerKey.map(toPublic), null, 2) + "\n",
);

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const rows = answerKey.map(
  (p) =>
    `  (${q(p.id)}, ${q(p.topic)}, ${q(p.kind)}, ${p.answer}, ${q(p.tag)}, ${q(JSON.stringify(p.tags ?? {}))}::jsonb, ${q(p.explain)})`,
);
const sql = `-- GENERATED by \`npm run gen:problems\` from src/domain/{daa,ds,la}/problems.ts. Do not edit.
-- Contains every answer: keep it out of git and out of the website.
-- Run in Supabase (SQL Editor → New query → paste → Run) after schema.sql, and again after
-- changing any problem. Safe to re-run.
begin;

insert into public.problem_key (id, topic, kind, answer, tag, tags, explain) values
${rows.join(",\n")}
on conflict (id) do update set
  topic = excluded.topic, kind = excluded.kind, answer = excluded.answer,
  tag = excluded.tag, tags = excluded.tags, explain = excluded.explain;

delete from public.problem_key where id not in (${answerKey.map((p) => q(p.id)).join(", ")});

commit;
`;
writeFileSync("supabase/answer-key.sql", sql);
console.log(
  `Wrote ${answerKey.length} questions to src/domain/questions.json and supabase/answer-key.sql`,
);
